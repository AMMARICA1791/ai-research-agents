"""Small evidence-first evaluation gate for archived news excerpts.

Run: python -m research.news_eval --dossier research_output/news_research.json
This prepares human-authored questions; it does NOT fabricate gold answers or run Qwen.
"""
import argparse
import json
from pathlib import Path

def build(dossier, max_articles=5):
    rows=[]
    for case in dossier.get("article_cases", []):
        if case.get("retrieval_status") != "ARTICLE_RETRIEVED":
            continue
        ev=case.get("evidence", {})
        src=ev.get("source", {})
        excerpt=ev.get("source_excerpt", "")
        if not excerpt.strip() or not src.get("url"):
            continue
        article_id=len(rows)//3 + 1
        for kind in ("direct", "inference", "unanswerable"):
            rows.append({"article_id":article_id,"type":kind,"source_url":src["url"],
                         "source_sha256":src.get("sha256"),
                         "archived_excerpt":excerpt,
                         "question":"TODO: human-authored question",
                         "reference_answer":"TODO: human-authored answer or NOT_IN_SOURCE",
                         "reference_quote":"TODO: exact supporting quote (empty for unanswerable)",
                         "review_status":"NEEDS_HUMAN_GOLD_LABEL"})
        if article_id>=max_articles:
            break
    return {"status":"UNLABELED_EVALUATION_TEMPLATE","questions":rows,
            "notes":["No reference answers were generated by a model.",
                     "Source excerpt is truncated: results measure excerpt-grounded QA, not full-paper understanding.",
                     "Exact quote presence does not establish claim entailment."]}

def verify_quote(quote, excerpt):
    """Return exact or not_found; never promote fuzzy similarity to proof."""
    if not isinstance(quote,str) or len(quote.strip())<15:
        return "rejected_too_short"
    if not isinstance(excerpt,str):
        return "not_found"
    return "exact" if " ".join(quote.split()) in " ".join(excerpt.split()) else "not_found"

def validate(data):
    errors=[]
    if not isinstance(data, dict) or not isinstance(data.get("questions"), list) or not data["questions"]:
        return ["Evaluation set must contain at least one question"]
    for i,row in enumerate(data["questions"],1):
        if not isinstance(row, dict):
            errors.append(f"Q{i}: invalid question record")
            continue
        if row.get("type") not in ("direct", "inference", "unanswerable"):
            errors.append(f"Q{i}: invalid question type")
        if any(str(row.get(k,"")).startswith("TODO") or not row.get(k)
               for k in ("question","reference_answer","source_url")):
            errors.append(f"Q{i}: incomplete gold label")
        if row.get("type") in ("direct","inference") and verify_quote(
                row.get("reference_quote",""),row.get("archived_excerpt",""))!="exact":
            errors.append(f"Q{i}: no exact reference quote in archived excerpt")
        if row.get("type")=="unanswerable" and row.get("reference_answer")!="NOT_IN_SOURCE":
            errors.append(f"Q{i}: unanswerable gold answer must be NOT_IN_SOURCE")
    return errors

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--dossier",default="research_output/news_research.json")
    p.add_argument("--output",default="research_output/news_eval_template.json")
    p.add_argument("--check",help="Validate a human-completed evaluation JSON")
    args=p.parse_args()
    if args.check:
        errors=validate(json.loads(Path(args.check).read_text(encoding="utf-8")))
        for error in errors: print(error)
        print("Validation:", "PASS" if not errors else "FAIL", "errors:",len(errors))
        raise SystemExit(bool(errors))
    data=build(json.loads(Path(args.dossier).read_text(encoding="utf-8")))
    path=Path(args.output);path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print("Archived article excerpts:",len(data["questions"])//3)
    print("Questions awaiting independent human labels:",len(data["questions"]))
    print("Output:",path)

if __name__=="__main__":
    main()
